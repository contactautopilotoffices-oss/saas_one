-- 1. Function to atomically get the next ticket number for any property
CREATE OR REPLACE FUNCTION public.get_next_ticket_number(p_property_id UUID, p_org_id UUID DEFAULT NULL)
RETURNS TEXT AS $$
DECLARE
    v_next_seq INT;
    v_org_id UUID := p_org_id;
    v_org_init TEXT;
    v_prop_init TEXT;
    v_pad_len INT;
    v_seq_str TEXT;
BEGIN
    IF v_org_id IS NULL THEN
        SELECT organization_id INTO v_org_id FROM public.properties WHERE id = p_property_id;
    END IF;

    -- Atomically increment or initialize sequence counter
    INSERT INTO public.ticket_property_sequences (property_id, last_sequence, updated_at)
    VALUES (p_property_id, 1, NOW())
    ON CONFLICT (property_id) DO UPDATE
    SET last_sequence = ticket_property_sequences.last_sequence + 1,
        updated_at = NOW()
    RETURNING last_sequence INTO v_next_seq;

    v_org_init := public.get_ticket_org_initials(v_org_id);
    v_prop_init := public.get_ticket_property_initials(p_property_id);
    v_seq_str := v_next_seq::TEXT;
    v_pad_len := GREATEST(3, LENGTH(v_seq_str));

    RETURN v_org_init || '-' || v_prop_init || '-' || LPAD(v_seq_str, v_pad_len, '0');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Grant execution to authenticated users
GRANT EXECUTE ON FUNCTION public.get_next_ticket_number(UUID, UUID) TO authenticated, service_role;

-- 2. Hardened BEFORE INSERT Trigger Function
-- Ensures that whether ticket_number is generated by trigger OR provided by caller:
-- 1. Sequence table ticket_property_sequences is ALWAYS forwarded.
-- 2. property_sequence_number is ALWAYS populated.
-- 3. No counter can ever go backwards.
CREATE OR REPLACE FUNCTION public.generate_ticket_number()
RETURNS TRIGGER AS $$
DECLARE
    v_next_seq INT;
    v_org_init TEXT;
    v_prop_init TEXT;
    v_pad_len INT;
    v_seq_str TEXT;
    v_extracted_seq INT;
BEGIN
    -- Case 1: Caller provided a formatted ticket number (e.g. AP-ED-2652)
    IF NEW.ticket_number IS NOT NULL AND NEW.ticket_number != '' AND NEW.ticket_number !~ '^TKT-' THEN
        IF NEW.property_id IS NOT NULL THEN
            -- Extract trailing integer if present
            IF NEW.ticket_number ~ '-([0-9]+)$' THEN
                v_extracted_seq := (regexp_match(NEW.ticket_number, '-([0-9]+)$'))[1]::INT;
                IF v_extracted_seq IS NOT NULL THEN
                    NEW.property_sequence_number := COALESCE(NEW.property_sequence_number, v_extracted_seq);
                    -- Keep ticket_property_sequences in sync with highest seen number
                    INSERT INTO public.ticket_property_sequences (property_id, last_sequence, updated_at)
                    VALUES (NEW.property_id, v_extracted_seq, NOW())
                    ON CONFLICT (property_id) DO UPDATE
                    SET last_sequence = GREATEST(ticket_property_sequences.last_sequence, v_extracted_seq),
                        updated_at = NOW();
                END IF;
            END IF;
        END IF;
        RETURN NEW;
    END IF;

    -- Case 2: ticket_number is NULL, empty, or legacy TKT- format
    IF NEW.property_id IS NOT NULL THEN
        -- Atomically increment sequence for this property
        INSERT INTO public.ticket_property_sequences (property_id, last_sequence, updated_at)
        VALUES (NEW.property_id, 1, NOW())
        ON CONFLICT (property_id) DO UPDATE
        SET last_sequence = ticket_property_sequences.last_sequence + 1,
            updated_at = NOW()
        RETURNING last_sequence INTO v_next_seq;

        NEW.property_sequence_number := v_next_seq;

        -- Derive initials
        v_org_init := public.get_ticket_org_initials(NEW.organization_id);
        v_prop_init := public.get_ticket_property_initials(NEW.property_id);

        -- Dynamic padding
        v_seq_str := v_next_seq::TEXT;
        v_pad_len := GREATEST(3, LENGTH(v_seq_str));

        -- Preserve legacy number if incoming was TKT-...
        IF NEW.ticket_number IS NOT NULL AND NEW.ticket_number LIKE 'TKT-%' AND NEW.legacy_ticket_number IS NULL THEN
            NEW.legacy_ticket_number := NEW.ticket_number;
        END IF;

        NEW.ticket_number := v_org_init || '-' || v_prop_init || '-' || LPAD(v_seq_str, v_pad_len, '0');
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Re-attach Trigger BEFORE INSERT
DROP TRIGGER IF EXISTS trg_generate_ticket_number ON public.tickets;
CREATE TRIGGER trg_generate_ticket_number
BEFORE INSERT ON public.tickets
FOR EACH ROW
EXECUTE FUNCTION public.generate_ticket_number();

